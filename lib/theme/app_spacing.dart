/// Spacing scale — use these named constants instead of raw numeric values.
///
/// Values follow a 4-point grid. Every padding / margin / gap in the app
/// should reference one of these constants (rounded to the nearest value).
class AppSpacing {
  AppSpacing._();

  static const double xs = 4;
  static const double sm = 8;
  static const double md = 12;
  static const double lg = 16;
  static const double xl = 24;
  static const double xxl = 32;
}
