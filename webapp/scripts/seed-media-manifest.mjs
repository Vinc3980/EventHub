/**
 * Regenerates src/services/seedMedia.ts from the imported media bundle.
 *
 *   npm run seed:media   (or: node scripts/seed-media-manifest.mjs)
 *
 * Source: public/seed/wallpapers/ — drop files in (or swap the whole folder)
 * and rerun. Rules:
 *   - images: imported as-is, no size limit (they are static files, not data URLs);
 *   - videos: must stay under MAX_VIDEO_BYTES — oversized clips are skipped and
 *     reported, so they can be re-encoded with ffmpeg before seeding.
 *
 * Requires the devDependency `ffmpeg-static` only when you re-encode clips by hand.
 */
import { readdirSync, statSync, writeFileSync } from 'node:fs';
import { join } from 'node:path';
import { fileURLToPath } from 'node:url';

/** Seed videos stay ≤ 10 MB; images have no limit. */
const MAX_VIDEO_BYTES = 10_000_000;

const IMAGE_EXT = new Set(['.avif', '.gif', '.jpeg', '.jpg', '.png', '.webp']);
const VIDEO_EXT = new Set(['.m4v', '.mov', '.mp4', '.webm']);

const dir = fileURLToPath(new URL('../public/seed/wallpapers/', import.meta.url));
const outFile = fileURLToPath(new URL('../src/services/seedMedia.ts', import.meta.url));

const images = [];
const videos = [];
const skipped = [];

for (const name of readdirSync(dir).sort((a, b) => a.localeCompare(b))) {
  const ext = name.slice(name.lastIndexOf('.')).toLowerCase();
  const bytes = statSync(join(dir, name)).size;
  if (VIDEO_EXT.has(ext)) {
    if (bytes > MAX_VIDEO_BYTES) skipped.push({ bytes, name });
    else videos.push(`/seed/wallpapers/${name}`);
  } else if (IMAGE_EXT.has(ext)) {
    images.push(`/seed/wallpapers/${name}`);
  }
}

for (const clip of skipped) {
  const mb = (clip.bytes / 1_000_000).toFixed(1);
  console.warn(`skipped video over ${MAX_VIDEO_BYTES / 1_000_000} MB: ${clip.name} (${mb} MB)`);
}

const list = (urls) => (urls.length === 0 ? '[]' : `[\n${urls.map((u) => `  '${u}',`).join('\n')}\n]`);

const contents = `// Generated by \`npm run seed:media\` (scripts/seed-media-manifest.mjs) — do not edit.
// Imported media bundle: public/seed/wallpapers/ (images unlimited, videos ≤ 10 MB).

/** Seed videos must stay at or under this size; images are imported without a limit. */
export const SEED_VIDEO_MAX_BYTES = ${MAX_VIDEO_BYTES.toLocaleString('en-US').replace(/,/g, '_')};

/** Imported images, sorted — used for event covers and image posts. */
export const WALLPAPER_IMAGES: string[] = ${list(images)};

/** Imported videos (every clip is ≤ SEED_VIDEO_MAX_BYTES) — used for video posts. */
export const WALLPAPER_VIDEOS: string[] = ${list(videos)};
`;

writeFileSync(outFile, contents);
console.log(
  `wrote src/services/seedMedia.ts — ${images.length} images, ${videos.length} videos` +
    (skipped.length > 0 ? `, ${skipped.length} skipped` : ''),
);
